import 'dart:math';
import '../models/pyramid_lesson.dart';

class PyramidEngine {
  static int _comb(int n, int k) {
    int r = 1;
    for (int i = 1; i <= k; i++) {
      r = r * (n - k + i) ~/ i;
    }
    return r;
  }

  static List<List<int>> build(List<int> base) {
    final n = base.length;
    final rows = List<List<int>>.filled(n, []);
    rows[n - 1] = List<int>.from(base);
    for (int r = n - 2; r >= 0; r--) {
      rows[r] = List.generate(r + 1, (c) => rows[r + 1][c] + rows[r + 1][c + 1]);
    }
    return rows;
  }

  // given: moi phan tu [hang, cot, gia tri]. Tra ve moi thap (danh sach cac hang) khop.
  static List<List<List<int>>> solve(int levels, List<List<int>> given,
      {int maxSolutions = 50, int cap = 99}) {
    final n = levels;
    final coef = List.generate(n, (c) => _comb(n - 1, c));
    int? topVal;
    for (final g in given) {
      if (g[0] == 0 && g[1] == 0) topVal = g[2];
    }
    final limit = topVal ?? cap;
    final out = <List<List<int>>>[];
    final base = List<int>.filled(n, 0);

    void rec(int idx, int total) {
      if (out.length >= maxSolutions) return;
      if (idx == n) {
        if (topVal != null && total != topVal) return;
        final rows = build(base);
        for (final g in given) {
          if (rows[g[0]][g[1]] != g[2]) return;
        }
        out.add(rows);
        return;
      }
      for (int v = 1; v <= limit; v++) {
        final t = total + coef[idx] * v;
        if (t > limit) break;
        base[idx] = v;
        rec(idx + 1, t);
      }
    }

    rec(0, 0);
    return out;
  }

  static PyramidLesson? generate({int? level}) {
    final rng = Random();
    final lv = level ?? (1 + rng.nextInt(3));
    final multi = rng.nextInt(3) == 0;
    final levels = lv == 1 ? 3 : (lv == 2 ? 4 : 4 + rng.nextInt(2));

    for (int attempt = 0; attempt < 200; attempt++) {
      final maxBase = lv == 1 ? 9 : (lv == 2 ? 9 : 12);
      final base = List.generate(levels, (_) => 1 + rng.nextInt(maxBase));
      final rows = build(base);
      final all = <List<int>>[];
      for (int r = 0; r < levels; r++) {
        for (int c = 0; c <= r; c++) {
          all.add([r, c, rows[r][c]]);
        }
      }

      if (multi) {
        if (levels != 3) continue;
        // dinh va mot o day: de bai co nhieu cach dien
        final keep = [
          [0, 0, rows[0][0]],
          [2, 1, rows[2][1]],
        ];
        final sols = solve(levels, keep);
        if (sols.length >= 2 && sols.length <= 6) {
          return PyramidLesson(
            id: 'pyr_${DateTime.now().millisecondsSinceEpoch}',
            title: {
              'ja': 'かずの つみ木 じどう（ぜんぶ）',
              'en': 'Auto Tower (find all)',
              'vi': 'Tháp số tự động (tìm đủ cách)',
            },
            question: _q(true),
            levels: levels,
            given: keep,
            multi: true,
            difficulty: lv,
            isAutoGenerated: true,
          );
        }
        continue;
      }

      final shuffled = List<List<int>>.from(all)..shuffle(rng);
      final keepCount = max(levels, levels + 2 - lv);
      final keep = shuffled.take(keepCount).toList();
      final sols = solve(levels, keep, maxSolutions: 3);
      if (sols.length == 1) {
        return PyramidLesson(
          id: 'pyr_${DateTime.now().millisecondsSinceEpoch}',
          title: {
            'ja': 'かずの つみ木 じどう ${levels}だん',
            'en': 'Auto Tower $levels levels',
            'vi': 'Tháp số tự động $levels tầng',
          },
          question: _q(false),
          levels: levels,
          given: keep,
          multi: false,
          difficulty: lv,
          isAutoGenerated: true,
        );
      }
    }
    return null;
  }

  static Map<String, String> _q(bool multi) => multi
      ? {
          'ja': 'なにも かいていない つみ木に かずを 入れます。「0」は 入れては いけません。入れかたを ぜんぶ かきましょう。',
          'en': 'Fill in the empty blocks without using 0. Find ALL the ways.',
          'vi': 'Điền số vào các ô trống, không dùng số 0. Hãy tìm TẤT CẢ các cách điền.',
        }
      : {
          'ja': 'となりどうしの 2つの つみ木の かずを あわせると、上のだんの つみ木に かいてある かずに なります。なにも かいていない つみ木に かずを かきましょう。',
          'en': 'Two neighbouring blocks add up to the block above. Fill in the empty blocks.',
          'vi': 'Hai ô cạnh nhau cộng lại bằng ô nằm trên. Hãy điền các ô còn trống.',
        };
}
