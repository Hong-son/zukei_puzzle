import 'dart:math';
import '../models/back_lesson.dart';
import '../models/pick_lesson.dart';
import 'dice_engine.dart';

class Dice3DEngine {
  static const _pos = <String, List<int>>{
    'top': [0, 0, 1],
    'bottom': [0, 0, -1],
    'N': [0, 1, 0],
    'S': [0, -1, 0],
    'E': [1, 0, 0],
    'W': [-1, 0, 0],
  };

  // Gap hinh khai trien, tra ve huong->so (mat cells[0] o duoi)
  static Map<String, int>? orient(List<List<int>> cells, List<int> values) {
    final index = <String, int>{};
    for (int i = 0; i < cells.length; i++) {
      index['${cells[i][0]}_${cells[i][1]}'] = i;
    }
    Map<String, String> start = {for (final k in ['top', 'bottom', 'N', 'S', 'W', 'E']) k: k};
    final state = <int, Map<String, String>>{0: start};
    final faces = <int, String>{0: 'bottom'};
    final queue = <int>[0];
    while (queue.isNotEmpty) {
      final cur = queue.removeAt(0);
      for (final e in DiceEngine.dirs.entries) {
        final nb = index['${cells[cur][0] + e.value[0]}_${cells[cur][1] + e.value[1]}'];
        if (nb != null && !state.containsKey(nb)) {
          state[nb] = _roll(state[cur]!, e.key);
          faces[nb] = state[nb]!['bottom']!;
          queue.add(nb);
        }
      }
    }
    if (faces.length != 6 || faces.values.toSet().length != 6) return null;
    return {for (int i = 0; i < 6; i++) faces[i]!: values[i]};
  }

  static Map<String, String> _roll(Map<String, String> o, String d) {
    if (d == 'E') {
      return {'bottom': o['E']!, 'E': o['top']!, 'top': o['W']!, 'W': o['bottom']!, 'N': o['N']!, 'S': o['S']!};
    }
    if (d == 'W') {
      return {'bottom': o['W']!, 'W': o['top']!, 'top': o['E']!, 'E': o['bottom']!, 'N': o['N']!, 'S': o['S']!};
    }
    if (d == 'N') {
      return {'bottom': o['N']!, 'N': o['top']!, 'top': o['S']!, 'S': o['bottom']!, 'W': o['W']!, 'E': o['E']!};
    }
    return {'bottom': o['S']!, 'S': o['top']!, 'top': o['N']!, 'N': o['bottom']!, 'W': o['W']!, 'E': o['E']!};
  }

  static List<int> canon(List<int> t) {
    int mi = 0;
    for (int i = 1; i < 3; i++) {
      if (t[i] < t[mi]) mi = i;
    }
    return [t[mi], t[(mi + 1) % 3], t[(mi + 2) % 3]];
  }

  static String key(List<int> t) => canon(t).join(',');

  // 8 dinh: bo ba (x, y, z) da chuan hoa theo chieu nhat quan
  static Set<String> corners(Map<String, int> o) {
    final res = <String>{};
    for (final tz in ['top', 'bottom']) {
      for (final ty in ['N', 'S']) {
        for (final tx in ['E', 'W']) {
          final a = _pos[tx]!, b = _pos[ty]!, c = _pos[tz]!;
          final det = a[0] * (b[1] * c[2] - b[2] * c[1]) -
              a[1] * (b[0] * c[2] - b[2] * c[0]) +
              a[2] * (b[0] * c[1] - b[1] * c[0]);
          final t = [o[tx]!, o[ty]!, o[tz]!];
          res.add(key(det > 0 ? t : [t[0], t[2], t[1]]));
        }
      }
    }
    return res;
  }

  // Xuc xac nhin thay (trai, phai, tren) co the tao ra tu hinh khai trien?
  static bool matches(Map<String, int> o, List<int> option) {
    final c = corners(o);
    return c.contains(key(option));
  }

  static List<int> shuffledValues(List<List<int>> cells, Random rng) {
    final probe = orient(cells, [0, 1, 2, 3, 4, 5])!;
    final inv = {for (final e in probe.entries) e.value: e.key};
    final nums = [
      [1, 6],
      [2, 5],
      [3, 4]
    ]..shuffle(rng);
    final v = List<int>.filled(6, 0);
    final seen = <int>{};
    int p = 0;
    for (int i = 0; i < 6; i++) {
      if (seen.contains(i)) continue;
      final j = probe[DiceEngine.opp[inv[i]!]!]!;
      var a = nums[p][0], b = nums[p][1];
      if (rng.nextBool()) {
        final t = a;
        a = b;
        b = t;
      }
      v[i] = a;
      v[j] = b;
      seen.add(i);
      seen.add(j);
      p++;
    }
    return v;
  }

  static BackLesson generateBack({int? level}) {
    final rng = Random();
    final lv = level ?? (1 + rng.nextInt(5));
    final n = 1 + lv + rng.nextInt(2);
    final fronts = List.generate(n, (_) => 1 + rng.nextInt(6));
    return BackLesson(
      id: 'back_${DateTime.now().millisecondsSinceEpoch}',
      title: {
        'ja': 'うしろから みると ${n}こ',
        'en': 'View from behind: $n dice',
        'vi': 'Nhìn từ phía sau: $n xúc xắc',
      },
      question: _qBack,
      fronts: fronts,
      difficulty: min(3, (lv + 1) ~/ 2),
      isAutoGenerated: true,
    );
  }

  static const Map<String, String> _qBack = {
    'ja': 'さいころには 1〜6の 目が あって、むかいあう 目の かずを あわせると 7に なります。まえから 見える 目が 下のように ならんで います。うしろから 見える 目の かずは あわせて いくつですか。',
    'en': 'Opposite faces add up to 7. The faces seen from the front are shown. What is the total of the faces seen from behind?',
    'vi': 'Hai mặt đối nhau cộng bằng 7. Các mặt nhìn từ phía trước như hình. Tổng các mặt nhìn từ phía sau là bao nhiêu?',
  };

  static const Map<String, String> _qPick = {
    'ja': '右は さいころを きりひらいた ものです。これを くみたてたときに できる さいころを えらびましょう。',
    'en': 'This is a dice cut open. Choose the dice that can be made by folding it.',
    'vi': 'Đây là xúc xắc được cắt ra. Hãy chọn xúc xắc có thể tạo được khi gấp hình này.',
  };

  static PickLesson? generatePick({int? level}) {
    final rng = Random();
    final lv = level ?? (1 + rng.nextInt(3));
    final nets = DiceEngine.nets();
    for (int attempt = 0; attempt < 60; attempt++) {
      final cells = nets[rng.nextInt(nets.length)].map((c) => c.toList()).toList();
      final values = shuffledValues(cells, rng);
      final o = orient(cells, values);
      if (o == null) continue;
      final good = corners(o).toList()..shuffle(rng);
      final answer = good.first.split(',').map(int.parse).toList();
      final optionCount = 2 + lv;
      final wrongs = <List<int>>[];
      int guard = 0;
      while (wrongs.length < optionCount - 1 && guard < 300) {
        guard++;
        final base = good[rng.nextInt(good.length)].split(',').map(int.parse).toList();
        List<int> t;
        if (rng.nextBool()) {
          t = [base[0], base[2], base[1]];
        } else {
          t = [1 + rng.nextInt(6), 1 + rng.nextInt(6), 1 + rng.nextInt(6)];
          if (t.toSet().length < 3) continue;
        }
        if (matches(o, t)) continue;
        if (wrongs.any((w) => key(w) == key(t))) continue;
        wrongs.add(t);
      }
      if (wrongs.length < optionCount - 1) continue;
      final options = [answer, ...wrongs]..shuffle(rng);
      final correct = options.indexWhere((t) => key(t) == key(answer));
      return PickLesson(
        id: 'pick_${DateTime.now().millisecondsSinceEpoch}',
        title: {
          'ja': 'どの さいころ？ $optionCountこ',
          'en': 'Which dice? ($optionCount choices)',
          'vi': 'Xúc xắc nào? ($optionCount lựa chọn)',
        },
        question: _qPick,
        cells: cells,
        values: values,
        options: options,
        correct: correct,
        difficulty: lv,
        isAutoGenerated: true,
      );
    }
    return null;
  }
}
