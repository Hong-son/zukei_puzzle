class PyramidLesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final int levels;
  final List<List<int>> given;
  final bool multi;
  final int difficulty;
  final bool isAutoGenerated;

  const PyramidLesson({
    required this.id,
    required this.title,
    required this.question,
    required this.levels,
    required this.given,
    this.multi = false,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'levels': levels,
        'given': given,
        'multi': multi,
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory PyramidLesson.fromJson(Map<String, dynamic> j) => PyramidLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        levels: j['levels'] as int,
        given: (j['given'] as List)
            .map((g) => (g as List).map((e) => e as int).toList())
            .toList(),
        multi: (j['multi'] as bool?) ?? false,
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
