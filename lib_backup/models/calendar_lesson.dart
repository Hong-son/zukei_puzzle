class CalendarQuestion {
  final String type;
  final int year;
  final int month;
  final int day;
  final int weekday;
  final int amount;
  final int month2;
  final int day2;
  final bool inclusive;

  const CalendarQuestion({
    required this.type,
    this.year = 0,
    this.month = 1,
    this.day = 1,
    this.weekday = 0,
    this.amount = 0,
    this.month2 = 0,
    this.day2 = 0,
    this.inclusive = false,
  });

  Map<String, dynamic> toJson() => {
        'type': type,
        'year': year,
        'month': month,
        'day': day,
        'weekday': weekday,
        'amount': amount,
        'month2': month2,
        'day2': day2,
        'inclusive': inclusive,
      };

  factory CalendarQuestion.fromJson(Map<String, dynamic> j) => CalendarQuestion(
        type: j['type'] as String,
        year: (j['year'] as int?) ?? 0,
        month: j['month'] as int,
        day: j['day'] as int,
        weekday: j['weekday'] as int,
        amount: j['amount'] as int,
        month2: j['month2'] as int,
        day2: j['day2'] as int,
        inclusive: (j['inclusive'] as bool?) ?? false,
      );
}

class CalendarLesson {
  final String id;
  final Map<String, String> title;
  final List<CalendarQuestion> questions;
  final int difficulty;
  final bool isAutoGenerated;
  final int year;

  const CalendarLesson({
    required this.id,
    required this.title,
    required this.questions,
    required this.difficulty,
    this.isAutoGenerated = false,
    this.year = 0,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'questions': questions.map((q) => q.toJson()).toList(),
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
        'year': year,
      };

  factory CalendarLesson.fromJson(Map<String, dynamic> j) => CalendarLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        questions: (j['questions'] as List)
            .map((q) => CalendarQuestion.fromJson(Map<String, dynamic>.from(q as Map)))
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
        year: (j['year'] as int?) ?? 0,
      );
}

