import 'dart:math';
import '../models/net_lesson.dart';
import 'dice_engine.dart';

class NetEngine {
  static List<List<List<int>>>? _all;

  static List<List<int>> _normalize(List<List<int>> cells) {
    final minR = cells.map((c) => c[0]).reduce(min);
    final minC = cells.map((c) => c[1]).reduce(min);
    final out = cells.map((c) => [c[0] - minR, c[1] - minC]).toList();
    out.sort((a, b) => a[0] != b[0] ? a[0].compareTo(b[0]) : a[1].compareTo(b[1]));
    return out;
  }

  static String _key(List<List<int>> cells) =>
      cells.map((c) => '${c[0]}_${c[1]}').join(',');

  static List<List<List<int>>> _variants(List<List<int>> cells) {
    final fs = <List<int> Function(int, int)>[
      (r, c) => [r, c],
      (r, c) => [r, -c],
      (r, c) => [-r, c],
      (r, c) => [-r, -c],
      (r, c) => [c, r],
      (r, c) => [c, -r],
      (r, c) => [-c, r],
      (r, c) => [-c, -r],
    ];
    return fs.map((f) => _normalize(cells.map((p) => f(p[0], p[1])).toList())).toList();
  }

  // Tat ca 35 hexomino
  static List<List<List<int>>> allHexominoes() {
    if (_all != null) return _all!;
    var current = <String, List<List<int>>>{
      '0_0': [[0, 0]]
    };
    for (int step = 0; step < 5; step++) {
      final next = <String, List<List<int>>>{};
      for (final shape in current.values) {
        final set = shape.map((c) => '${c[0]}_${c[1]}').toSet();
        for (final c in shape) {
          for (final d in DiceEngine.dirs.values) {
            final nb = [c[0] + d[0], c[1] + d[1]];
            if (set.contains('${nb[0]}_${nb[1]}')) continue;
            final grown = _normalize([...shape, nb]);
            final canon = _variants(grown).map(_key).reduce((a, b) => a.compareTo(b) <= 0 ? a : b);
            next.putIfAbsent(canon, () => grown);
          }
        }
      }
      current = next;
    }
    _all = current.values.toList();
    return _all!;
  }

  static bool foldable(List<List<int>> cells) => DiceEngine.fold(cells) != null;

  static List<List<List<int>>> foldableNets() =>
      allHexominoes().where(foldable).toList();

  static List<List<List<int>>> nonFoldable() =>
      allHexominoes().where((h) => !foldable(h)).toList();

  // Ly do hinh khong gap duoc (de dung trong hint)
  static String reasonCode(List<List<int>> cells) {
    final set = cells.map((c) => '${c[0]}_${c[1]}').toSet();
    int longest = 1;
    for (final c in cells) {
      int run = 1;
      int r = c[0], col = c[1];
      while (set.contains('${r}_${col + 1}')) {
        run++;
        col++;
      }
      longest = max(longest, run);
      run = 1;
      r = c[0];
      col = c[1];
      while (set.contains('${r + 1}_$col')) {
        run++;
        r++;
      }
      longest = max(longest, run);
    }
    if (longest >= 5) return 'line5';
    for (final c in cells) {
      if (set.contains('${c[0]}_${c[1] + 1}') &&
          set.contains('${c[0] + 1}_${c[1]}') &&
          set.contains('${c[0] + 1}_${c[1] + 1}')) {
        return 'block2x2';
      }
    }
    return 'overlap';
  }

  static List<List<int>> randomVariant(List<List<int>> cells, Random rng) {
    final v = _variants(cells);
    return v[rng.nextInt(v.length)];
  }

  static NetLesson generate({int? level}) {
    final rng = Random();
    final lv = level ?? (1 + rng.nextInt(3));
    final total = 5 + lv + rng.nextInt(2);
    final good = foldableNets();
    final bad = nonFoldable();
    int badCount = 1 + rng.nextInt(max(1, total ~/ 2 - 0));
    badCount = badCount.clamp(1, total - 2);
    final shapes = <List<List<int>>>[];
    final goodPool = (good.toList()..shuffle(rng));
    final badPool = (bad.toList()..shuffle(rng));
    for (int i = 0; i < badCount; i++) {
      shapes.add(randomVariant(badPool[i % badPool.length], rng));
    }
    for (int i = 0; i < total - badCount; i++) {
      shapes.add(randomVariant(goodPool[i % goodPool.length], rng));
    }
    shapes.shuffle(rng);
    return NetLesson(
      id: 'net_${DateTime.now().millisecondsSinceEpoch}',
      title: {
        'ja': 'さいころの かたち じどう',
        'en': 'Auto Dice Nets',
        'vi': 'Tìm hình không gấp được (tự động)',
      },
      question: {
        'ja': 'せんで おりまげて くみ立てても さいころの かたちに ならない ものを ぜんぶ えらびましょう。',
        'en': 'Choose ALL shapes that cannot be folded into a dice.',
        'vi': 'Chọn TẤT CẢ hình không thể gấp thành xúc xắc.',
      },
      shapes: shapes,
      difficulty: lv,
      isAutoGenerated: true,
    );
  }
}

