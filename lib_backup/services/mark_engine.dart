import 'dart:math';
import '../models/mark_lesson.dart';
import 'dice_engine.dart';

class MarkEngine {
  static List<List<int>> transform(List<List<int>> cells, Random rng) {
    final fs = <List<int> Function(int, int)>[
      (r, c) => [r, c],
      (r, c) => [r, -c],
      (r, c) => [-r, c],
      (r, c) => [-r, -c],
      (r, c) => [c, r],
      (r, c) => [c, -r],
      (r, c) => [-c, r],
      (r, c) => [-c, -r],
    ];
    final f = fs[rng.nextInt(fs.length)];
    final t = cells.map((p) => f(p[0], p[1])).toList();
    final minR = t.map((c) => c[0]).reduce(min);
    final minC = t.map((c) => c[1]).reduce(min);
    return t.map((c) => [c[0] - minR, c[1] - minC]).toList();
  }

  static int oppositeOf(List<List<int>> cells, int idx) {
    for (final p in DiceEngine.oppositePairs(cells)) {
      if (p[0] == idx) return p[1];
      if (p[1] == idx) return p[0];
    }
    return -1;
  }

  static List<int> sideFaces(List<List<int>> cells, int idx) {
    final opp = oppositeOf(cells, idx);
    return [
      for (int i = 0; i < cells.length; i++)
        if (i != idx && i != opp) i
    ];
  }

  static bool adjacent(List<int> a, List<int> b) =>
      (a[0] - b[0]).abs() + (a[1] - b[1]).abs() == 1;

  static MarkLesson generate({int? level}) {
    final rng = Random();
    final lv = level ?? (1 + rng.nextInt(3));
    final count = min(6, 2 + lv + rng.nextInt(2));
    final all = DiceEngine.nets();
    final nets = <List<List<int>>>[];
    final marks = <int>[];
    for (int i = 0; i < count; i++) {
      final base = all[rng.nextInt(all.length)];
      nets.add(transform(base, rng));
      marks.add(rng.nextInt(6));
    }
    return MarkLesson(
      id: 'mark_${DateTime.now().millisecondsSinceEpoch}',
      title: {
        'ja': 'むかいあう めん じどう',
        'en': 'Auto Opposite Face',
        'vi': 'Tìm mặt đối diện (tự động)',
      },
      question: {
        'ja': '◎の ある めんと むかいあう めんは どれですか。そのめんにも ◎を かきましょう。',
        'en': 'Which face is opposite the ◎ face? Draw a ◎ on it too.',
        'vi': 'Mặt nào đối diện với mặt có ◎? Hãy vẽ ◎ vào mặt đó.',
      },
      nets: nets,
      marks: marks,
      difficulty: lv,
      isAutoGenerated: true,
    );
  }
}

