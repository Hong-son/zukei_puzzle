// Bai "はんぶんだけぬる": moi bai co nhieu hinh vuong, moi hinh gom cac da giac duoc to mau.
// Toa do nguyen tren luoi 0..4 (hinh vuong 4x4), truc y huong xuong.
class HalfLesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final List<List<List<List<int>>>> figures;
  final int difficulty;
  final bool isAutoGenerated;

  const HalfLesson({
    required this.id,
    required this.title,
    required this.question,
    required this.figures,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'figures': figures,
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory HalfLesson.fromJson(Map<String, dynamic> j) => HalfLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        figures: (j['figures'] as List)
            .map((f) => (f as List)
                .map((poly) => (poly as List)
                    .map((pt) => (pt as List).map((v) => v as int).toList())
                    .toList())
                .toList())
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
