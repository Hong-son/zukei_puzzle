class DiceLesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final List<List<int>> cells;
  final Map<int, int> values;
  final List<int> hiddenIdx;
  final List<String> labels;
  final int difficulty;
  final bool isAutoGenerated;

  const DiceLesson({
    required this.id,
    required this.title,
    required this.question,
    required this.cells,
    required this.values,
    required this.hiddenIdx,
    required this.labels,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'cells': cells,
        'values': values.map((k, v) => MapEntry(k.toString(), v)),
        'hiddenIdx': hiddenIdx,
        'labels': labels,
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory DiceLesson.fromJson(Map<String, dynamic> j) => DiceLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        cells: (j['cells'] as List)
            .map((c) => (c as List).map((e) => e as int).toList())
            .toList(),
        values: (j['values'] as Map)
            .map((k, v) => MapEntry(int.parse(k as String), v as int)),
        hiddenIdx: (j['hiddenIdx'] as List).map((e) => e as int).toList(),
        labels: (j['labels'] as List).map((e) => e as String).toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
