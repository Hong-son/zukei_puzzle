// Bai 算数 "とけいの はり".
// type 'set': cho gio (hour, minute) -> be keo kim ngan va kim dai ve dung vi tri.
// type 'draw': kim dai bi mat, chi con kim ngan -> be ve kim dai va viet gio.
// Nhom "じこくと じかん" (ClockLesson.kind == 'span'):
// type 'until': dong ho chi hour:minute -> con bao nhieu gio/phut den extra[0] gio (vd 12 = trua).
// type 'rate' : hour = gio bat dau, extra = [gio het dau, so trang, gio het sau, kieu cau, ten] -> tong so trang.
class ClockQuestion {
  final String type; // 'set' | 'draw' | 'until' | 'rate'
  final int hour; // 1..12
  final int minute; // 0..55 (boi cua 5)
  final List<int> extra; // tham so them (xem tren)

  const ClockQuestion({required this.type, required this.hour, this.minute = 0, this.extra = const []});

  Map<String, dynamic> toJson() => {'type': type, 'hour': hour, 'minute': minute, 'x': extra};

  factory ClockQuestion.fromJson(Map<String, dynamic> j) => ClockQuestion(
        type: j['type'] as String,
        hour: j['hour'] as int,
        minute: (j['minute'] as int?) ?? 0,
        extra: [for (final e in (j['x'] as List? ?? const [])) (e as num).toInt()],
      );
}

class ClockLesson {
  final String id;
  final Map<String, String> title;
  final List<ClockQuestion> questions;
  final int difficulty;
  final bool isAutoGenerated;
  final String kind; // 'hands' (とけいの はり) | 'span' (じこくと じかん)

  const ClockLesson({
    required this.id,
    required this.title,
    required this.questions,
    required this.difficulty,
    this.isAutoGenerated = false,
    this.kind = 'hands',
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'questions': questions.map((q) => q.toJson()).toList(),
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
        'kind': kind,
      };

  factory ClockLesson.fromJson(Map<String, dynamic> j) => ClockLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        questions: (j['questions'] as List)
            .map((q) => ClockQuestion.fromJson(Map<String, dynamic>.from(q as Map)))
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
        kind: (j['kind'] as String?) ?? 'hands',
      );
}
