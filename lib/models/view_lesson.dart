// Bai tap nhin hinh: kind 'water' (水めんのかたち: xep thu tu luong nuoc nhin tu tren xuong)
// va 'shadow' (かげの正たい: doan vat tu 3 cai bong).
class ViewItem {
  final String label; // vd: （1）
  final Map<String, dynamic> data;
  const ViewItem({required this.label, required this.data});

  Map<String, dynamic> toJson() => {'label': label, 'data': data};

  factory ViewItem.fromJson(Map<String, dynamic> j) => ViewItem(
        label: j['label'] as String,
        data: Map<String, dynamic>.from(j['data'] as Map),
      );
}

class ViewLesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final String kind; // 'water' | 'shadow'
  final List<ViewItem> items;
  final int difficulty;
  final bool isAutoGenerated;
  final List<String> bank; // 'shadow': cac vat de chon, theo thu tu ①②...

  const ViewLesson({
    required this.id,
    required this.title,
    required this.question,
    required this.kind,
    required this.items,
    required this.difficulty,
    this.isAutoGenerated = false,
    this.bank = const [],
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'kind': kind,
        'items': items.map((e) => e.toJson()).toList(),
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
        if (bank.isNotEmpty) 'bank': bank,
      };

  factory ViewLesson.fromJson(Map<String, dynamic> j) => ViewLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        kind: j['kind'] as String,
        items: (j['items'] as List)
            .map((e) => ViewItem.fromJson(Map<String, dynamic>.from(e as Map)))
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
        bank: ((j['bank'] as List?) ?? const []).map((e) => e as String).toList(),
      );
}
