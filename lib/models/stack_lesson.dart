// Bai xuc xac xep chong / xep hang (4 dang: stack, same, line, around).
//
// Toa do o: [x, y, z]  x = sang phai, y = ra phia sau (y = 0 la hang truoc), z = chieu cao.
// Moi vien xuc xac co 3 mat nhin thay trong hinh: faces[i] = [tren, truoc, phai].
// Ba mat con lai (duoi, sau, trai) luon bang 7 tru di mat doi dien.
// covered[i] = [tren, truoc, phai]: true neu mat do bi dan tem (khong thay cham).
class StackLesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final String kind; // 'stack' | 'same' | 'line' | 'around'
  final String ask; // 'around' (tong cham nhin thay) | 'left' (mat nhin tu ben trai)
  final List<List<int>> cells;
  final List<List<int>> faces;
  final List<List<bool>> covered;
  final int difficulty;
  final bool isAutoGenerated;

  const StackLesson({
    required this.id,
    required this.title,
    required this.question,
    required this.kind,
    required this.ask,
    required this.cells,
    required this.faces,
    required this.covered,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  bool get hasSticker {
    for (final c in covered) {
      if (c.contains(true)) return true;
    }
    return false;
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'kind': kind,
        'ask': ask,
        'cells': cells,
        'faces': faces,
        'covered': covered,
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory StackLesson.fromJson(Map<String, dynamic> j) => StackLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        kind: j['kind'] as String,
        ask: j['ask'] as String,
        cells: (j['cells'] as List)
            .map((c) => (c as List).map((v) => v as int).toList())
            .toList(),
        faces: (j['faces'] as List)
            .map((c) => (c as List).map((v) => v as int).toList())
            .toList(),
        covered: (j['covered'] as List)
            .map((c) => (c as List).map((v) => v as bool).toList())
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
