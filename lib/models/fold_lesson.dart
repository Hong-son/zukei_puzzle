// Bai 算数 "たいしょうな かたち": gap giay lam 4, cat mot phan, mo ra 1 lan / 2 lan -> to phan bi cat.
// shape: 'sq' = to giay hinh vuong, 'tri' = to giay hinh vuong xoay 45 do (gap xong thanh tam giac vuong can).
// cut: danh sach ma manh tam giac bi cat tren to giay da gap (xem FoldEngine.code).
class FoldQuestion {
  final String shape; // 'sq' | 'tri'
  final List<int> cut;
  const FoldQuestion({required this.shape, required this.cut});

  Map<String, dynamic> toJson() => {'shape': shape, 'cut': cut};

  factory FoldQuestion.fromJson(Map<String, dynamic> j) => FoldQuestion(
        shape: j['shape'] as String,
        cut: [for (final e in (j['cut'] as List)) (e as num).toInt()],
      );
}

class FoldLesson {
  final String id;
  final Map<String, String> title;
  final List<FoldQuestion> questions;
  final int difficulty;
  final bool isAutoGenerated;

  const FoldLesson({
    required this.id,
    required this.title,
    required this.questions,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'questions': questions.map((q) => q.toJson()).toList(),
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory FoldLesson.fromJson(Map<String, dynamic> j) => FoldLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        questions: (j['questions'] as List)
            .map((q) => FoldQuestion.fromJson(Map<String, dynamic>.from(q as Map)))
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
