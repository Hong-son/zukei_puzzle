// Bai tap 国語: kind 'kaki' (viet chu Han vao o) va 'yomi' (viet cach doc bang hiragana).
//
// Moi cau (KokugoItem) gom nhieu doan (KokugoPart):
// - doan thuong: text la chu hien thi.
// - doan blank cua 'kaki': text = chu Han dap an (moi ky tu 1 o), reads = katakana ghi tren moi o.
// - doan blank cua 'yomi': text = chu Han bi gach chan, reads = cac cach doc hiragana duoc chap nhan.
class KokugoPart {
  final String text;
  final bool blank;
  final List<String> reads;
  const KokugoPart(this.text, {this.blank = false, this.reads = const []});

  Map<String, dynamic> toJson() => {'t': text, 'b': blank, 'r': reads};

  factory KokugoPart.fromJson(Map<String, dynamic> j) => KokugoPart(
        j['t'] as String,
        blank: (j['b'] as bool?) ?? false,
        reads: ((j['r'] as List?) ?? const []).map((e) => e as String).toList(),
      );
}

class KokugoItem {
  final String label; // vd: ① hoac ①ア
  final List<KokugoPart> parts;
  const KokugoItem({required this.label, required this.parts});

  Map<String, dynamic> toJson() => {
        'label': label,
        'parts': parts.map((p) => p.toJson()).toList(),
      };

  factory KokugoItem.fromJson(Map<String, dynamic> j) => KokugoItem(
        label: j['label'] as String,
        parts: (j['parts'] as List)
            .map((p) => KokugoPart.fromJson(Map<String, dynamic>.from(p as Map)))
            .toList(),
      );

  // Doan blank dau tien (yomi chi co 1 doan blank)
  KokugoPart get firstBlank => parts.firstWhere((p) => p.blank);

  // Dap an chu Han cua 'kaki': ghep cac doan blank
  String get kanjiAnswer => parts.where((p) => p.blank).map((p) => p.text).join(' ');
}

class KokugoLesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final String kind; // 'kaki' | 'yomi'
  final List<KokugoItem> items;
  final int difficulty;
  final bool isAutoGenerated;

  const KokugoLesson({
    required this.id,
    required this.title,
    required this.question,
    required this.kind,
    required this.items,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'kind': kind,
        'items': items.map((e) => e.toJson()).toList(),
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory KokugoLesson.fromJson(Map<String, dynamic> j) => KokugoLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        kind: j['kind'] as String,
        items: (j['items'] as List)
            .map((e) => KokugoItem.fromJson(Map<String, dynamic>.from(e as Map)))
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
