// Bai "ましかくは いくつ？": luoi diem n cot x rows hang, hoi co bao nhieu hinh vuong theo tung dien tich.
class DotSquareLesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final int n; // so diem tren mot hang ngang (so cot)
  final int rows; // so diem tren mot cot doc (so hang)
  final List<int> areas;
  final int difficulty;
  final bool isAutoGenerated;

  const DotSquareLesson({
    required this.id,
    required this.title,
    required this.question,
    required this.n,
    required this.rows,
    required this.areas,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'n': n,
        'rows': rows,
        'areas': areas,
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory DotSquareLesson.fromJson(Map<String, dynamic> j) => DotSquareLesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        n: j['n'] as int,
        rows: (j['rows'] as int?) ?? (j['n'] as int),
        areas: (j['areas'] as List).map((e) => e as int).toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
