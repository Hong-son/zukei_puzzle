class PieceShape {
  final String id;
  final List<List<int>> cells;
  const PieceShape({required this.id, required this.cells});

  Map<String, dynamic> toJson() => {'id': id, 'cells': cells};

  factory PieceShape.fromJson(Map<String, dynamic> j) => PieceShape(
        id: j['id'] as String,
        cells: (j['cells'] as List)
            .map((c) => (c as List).map((e) => e as int).toList())
            .toList(),
      );
}

class Lesson {
  final String id;
  final Map<String, String> title;
  final Map<String, String> question;
  final int gridRows;
  final int gridCols;
  final List<List<List<int>>> fixedBlocks;
  final List<PieceShape> referencePieces;
  final int difficulty;
  final bool isAutoGenerated;

  const Lesson({
    required this.id,
    required this.title,
    required this.question,
    required this.gridRows,
    required this.gridCols,
    required this.fixedBlocks,
    required this.referencePieces,
    required this.difficulty,
    this.isAutoGenerated = false,
  });

  List<List<int>> get fixedCells => fixedBlocks.expand((b) => b).toList();

  Map<String, int> get available {
    final m = <String, int>{};
    for (final p in referencePieces) {
      m[p.id] = (m[p.id] ?? 0) + 1;
    }
    return m;
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'question': question,
        'gridRows': gridRows,
        'gridCols': gridCols,
        'fixedBlocks': fixedBlocks,
        'referencePieces': referencePieces.map((p) => p.toJson()).toList(),
        'difficulty': difficulty,
        'isAutoGenerated': isAutoGenerated,
      };

  factory Lesson.fromJson(Map<String, dynamic> j) => Lesson(
        id: j['id'] as String,
        title: Map<String, String>.from(j['title'] as Map),
        question: Map<String, String>.from(j['question'] as Map),
        gridRows: j['gridRows'] as int,
        gridCols: j['gridCols'] as int,
        fixedBlocks: (j['fixedBlocks'] as List)
            .map((b) => (b as List)
                .map((c) => (c as List).map((e) => e as int).toList())
                .toList())
            .toList(),
        referencePieces: (j['referencePieces'] as List)
            .map((p) => PieceShape.fromJson(Map<String, dynamic>.from(p as Map)))
            .toList(),
        difficulty: j['difficulty'] as int,
        isAutoGenerated: (j['isAutoGenerated'] as bool?) ?? false,
      );
}
