import 'dart:math';
import '../models/clock_lesson.dart';

class ClockEngine {
  // Goc (do, 0 = huong 12 gio, chieu kim dong ho) cua kim ngan luc hour:minute
  static double hourAngle(int hour, int minute) => (hour % 12) * 30.0 + minute * 0.5;

  // Goc cua kim dai
  static double minuteAngle(int minute) => minute * 6.0;

  // "2じ" / "2じ30ぷん" / "10じ5ふん"
  static String timeText(int hour, int minute) {
    if (minute == 0) return '${hour}じ';
    return '${hour}じ${minuteText(minute)}';
  }

  // 5ふん 10ぷん 15ふん ... (so tan cung 5 doc la ふん, tan cung 0 doc la ぷん)
  static String minuteText(int minute) => '$minute${minute % 10 == 5 ? 'ふん' : 'ぷん'}';

  // Khoang cach goc nho nhat giua hai goc (0..180)
  static double angleDiff(double a, double b) {
    final d = (a - b).abs() % 360;
    return d > 180 ? 360 - d : d;
  }

  static ClockLesson generate({int level = 1, Random? rng}) {
    final r = rng ?? Random();
    final lv = level < 1 ? 1 : (level > 3 ? 3 : level);
    final minutes = lv < 3 ? const [0, 30] : [for (var m = 0; m < 60; m += 5) m];
    final types = lv == 1
        ? ['set', 'set', 'set']
        : lv == 2
            ? ['draw', 'draw', 'draw', 'draw']
            : (['set', 'set', 'draw', 'draw', 'draw']..shuffle(r));
    final used = <String>{};
    final qs = <ClockQuestion>[];
    for (final t in types) {
      late int h;
      late int m;
      do {
        h = 1 + r.nextInt(12);
        m = minutes[r.nextInt(minutes.length)];
      } while (!used.add('$h:$m'));
      qs.add(ClockQuestion(type: t, hour: h, minute: m));
    }
    return ClockLesson(
      id: 'tk_${DateTime.now().microsecondsSinceEpoch}',
      title: {'ja': 'とけいの はり ✨', 'en': 'Clock Hands ✨', 'vi': 'Kim đồng hồ ✨'},
      questions: qs,
      difficulty: lv,
      isAutoGenerated: true,
    );
  }

  // --- じこくと じかん ---
  // 'until': con lai bao nhieu phut tu hour:minute den extra[0] gio
  static int untilMinutes(ClockQuestion q) => q.extra[0] * 60 - (q.hour * 60 + q.minute);

  // 'rate': tong so trang = so trang moi don vi * so don vi
  static int rateAnswer(ClockQuestion q) {
    final unit = q.extra[0] - q.hour; // so gio cua don vi mau
    final total = q.extra[2] - q.hour;
    return q.extra[1] * total ~/ unit;
  }

  static const List<String> rateNames = ['ゆかり', 'たろう', 'さくら', 'ひろし'];

  // Cau chu cua dang 'rate' theo ngon ngu (kieu 0 = しゅくだい, 1 = ほん)
  static String rateText(ClockQuestion q, String lang) {
    final name = rateNames[q.extra.length > 4 ? q.extra[4] % rateNames.length : 0];
    final v = q.extra.length > 3 ? q.extra[3] : 0;
    final s = q.hour, e1 = q.extra[0], p = q.extra[1], e2 = q.extra[2];
    if (lang == 'en') {
      return '$name worked on ${v == 0 ? 'homework' : 'a book'} from $s to $e1 o\'clock and finished $p pages. '
          'At the same speed, how many pages in total from $s to $e2 o\'clock?';
    }
    if (lang == 'vi') {
      return '$name ${v == 0 ? 'làm bài tập' : 'đọc sách'} từ $s giờ đến $e1 giờ được $p trang. '
          'Nếu giữ nguyên tốc độ, từ $s giờ đến $e2 giờ tổng cộng được bao nhiêu trang?';
    }
    return v == 0
        ? '$nameさんは ${s}じから ${e1}じの あいだに しゅくだいを ${p}ページ ときました。おなじ はやさで つづけて といていくと、${s}じから ${e2}じまでに ぜんぶで なんページ とけますか。'
        : '$nameさんは ${s}じから ${e1}じの あいだに ほんを ${p}ページ よみました。おなじ はやさで つづけて よんでいくと、${s}じから ${e2}じまでに ぜんぶで なんページ よめますか。';
  }

  static ClockLesson generateSpan({int level = 1, Random? rng}) {
    final r = rng ?? Random();
    final lv = level < 1 ? 1 : (level > 3 ? 3 : level);
    final minutes = lv < 3 ? const [0, 30] : [for (var m = 0; m < 60; m += 5) m];
    final nUntil = lv == 1 ? 3 : 2;
    final used = <String>{};
    final qs = <ClockQuestion>[];
    while (qs.length < nUntil) {
      final h = 7 + r.nextInt(5); // 7..11 (ごぜん)
      final m = minutes[r.nextInt(minutes.length)];
      if (!used.add('$h:$m')) continue;
      qs.add(ClockQuestion(type: 'until', hour: h, minute: m, extra: const [12]));
    }
    if (lv >= 2) {
      final d = lv == 3 ? 1 + r.nextInt(2) : 1; // don vi mau 1 hoac 2 gio
      final mult = 2 + r.nextInt(3); // gap may lan don vi
      final s = 1 + r.nextInt(12 - d * mult); // gio bat dau (gio ket thuc khong qua 12)
      final per = 2 + r.nextInt(4); // so trang moi gio
      qs.add(ClockQuestion(
          type: 'rate',
          hour: s,
          extra: [s + d, per * d, s + d * mult, r.nextInt(2), r.nextInt(rateNames.length)]));
    }
    return ClockLesson(
      id: 'tj_${DateTime.now().microsecondsSinceEpoch}',
      title: {'ja': 'じこくと じかん ✨', 'en': 'Time and Duration ✨', 'vi': 'Giờ và khoảng thời gian ✨'},
      questions: qs,
      difficulty: lv,
      isAutoGenerated: true,
      kind: 'span',
    );
  }

  // かがみの 中の とけい: gio:phut that (hour 1..12); man hinh se lat guong mat dong ho
  static ClockLesson generateMirror({int level = 1, Random? rng}) {
    final r = rng ?? Random();
    final lv = level < 1 ? 1 : (level > 3 ? 3 : level);
    final minutes = lv == 1 ? const [0, 30] : [for (var m = 0; m < 60; m += 5) m];
    final used = <String>{};
    final qs = <ClockQuestion>[];
    while (qs.length < 3) {
      final h = 1 + r.nextInt(12);
      final m = minutes[r.nextInt(minutes.length)];
      if (!used.add('$h:$m')) continue;
      qs.add(ClockQuestion(type: 'mirror', hour: h, minute: m));
    }
    return ClockLesson(
      id: 'tm_${DateTime.now().microsecondsSinceEpoch}',
      title: {'ja': 'かがみの 中の とけい ✨', 'en': 'Clock in the Mirror ✨', 'vi': 'Đồng hồ trong gương ✨'},
      questions: qs,
      difficulty: lv,
      isAutoGenerated: true,
      kind: 'mirror',
    );
  }
}
