import 'dart:math';
import '../models/dotsquare_lesson.dart';

class DotSquareEngine {
  // Moi hinh vuong co mot canh la vector (a, b) voi a >= 1, b >= 0 (duy nhat).
  // Dien tich = a*a + b*b. Hop bao co canh s = a + b. So vi tri = (cols - s) * (rows - s).
  static int count(int cols, int rows, int area) {
    int total = 0;
    for (int a = 1; a * a <= area; a++) {
      for (int b = 0; a * a + b * b <= area; b++) {
        if (a * a + b * b != area) continue;
        final s = a + b;
        if (s <= cols - 1 && s <= rows - 1) total += (cols - s) * (rows - s);
      }
    }
    return total;
  }

  // Tat ca hinh vuong co dien tich nay, moi hinh la 4 dinh [x, y]
  static List<List<List<int>>> allSquares(int cols, int rows, int area) {
    final res = <List<List<int>>>[];
    for (int a = 1; a * a <= area; a++) {
      for (int b = 0; a * a + b * b <= area; b++) {
        if (a * a + b * b != area) continue;
        final s = a + b;
        if (s > cols - 1 || s > rows - 1) continue;
        for (int y0 = 0; y0 + s <= rows - 1; y0++) {
          for (int x0 = 0; x0 + s <= cols - 1; x0++) {
            res.add([
              [x0 + b, y0],
              [x0 + s, y0 + b],
              [x0 + a, y0 + s],
              [x0, y0 + a],
            ]);
          }
        }
      }
    }
    return res;
  }

  // Cac dien tich co it nhat 1 hinh vuong tren luoi
  static List<int> possibleAreas(int cols, int rows) {
    final set = <int>{};
    final m = min(cols, rows) - 1;
    for (int a = 1; a <= m; a++) {
      for (int b = 0; a + b <= m; b++) {
        set.add(a * a + b * b);
      }
    }
    final list = set.toList()..sort();
    return list;
  }

  static const Map<String, String> question = {
    'ja': 'おなじ はばで ならんだ てんを つないで ましかくを つくります。いちばん 小さい ましかくの ひろさを 1 として、ひろさごとに ましかくが なんこ できるか こたえましょう。ななめの ましかくも あります。',
    'en': 'Join dots to make squares. The smallest square has area 1. How many squares of each area can you make? Tilted squares count too.',
    'vi': 'Nối các điểm để tạo hình vuông. Hình vuông nhỏ nhất có diện tích 1. Với mỗi diện tích, có thể tạo được bao nhiêu hình vuông? Hình vuông nghiêng cũng tính.',
  };

  static DotSquareLesson generate({int? level}) {
    final rng = Random();
    final lv = level ?? (1 + rng.nextInt(3));
    final cols = lv == 1 ? 4 : (lv == 2 ? 5 : 6);
    final rows = cols + rng.nextInt(2);
    final pool = possibleAreas(cols, rows)..shuffle(rng);
    final cnt = min(pool.length, 3 + lv);
    final areas = pool.sublist(0, cnt)..sort();
    return DotSquareLesson(
      id: 'dsq_${DateTime.now().millisecondsSinceEpoch}',
      title: {
        'ja': 'ましかくは いくつ？ $cols×$rows',
        'en': 'Count the Squares $cols×$rows',
        'vi': 'Đếm hình vuông $cols×$rows',
      },
      question: question,
      n: cols,
      rows: rows,
      areas: areas,
      difficulty: lv,
      isAutoGenerated: true,
    );
  }
}
